"""C: a mean-field switching model for the ongoing queue - an explicit two-state (free / queued) Markov chain per link
whose switching hazards are learned, coupled along the road through the neighbours' state probabilities.

Every member so far maps the history image straight to the future cells (CNN, transformer, STID, LightGBM). Here the
future is generated by a latent regime process, the structure of the task itself:

    encoder   per link, a temporal conv stack over the hour (v/vf, q/cap, observed, queued, static, time), then two
              light link convolutions (k 5) -> h_j (64)
    state     pi_0(j) = P(queued at T) from h_j and the last observed queue flag
    dynamics  for k = 1..F:  on_j, off_j = sigma(MLP[h_j, pi_{k-1}(j-2..j+2), k])
              pi_k(j) = pi_{k-1}(j) (1 - off_j) + (1 - pi_{k-1}(j)) on_j
              - persistence, onset and clearance are separate learned hazards; the queue can only spread through the
              neighbours' probabilities (mean-field coupling), never jump
    output    pi_k = P(queued at T + 5k); loss BCE + Lovasz on logit(pi_k), masked by eligibility
Trained on the training run's ongoing windows (true histories, as the HYDRA / longctx members); the lab stage scores
the official-like pool of both scored months with the observed histories, no adaptation (and with the note 106
pseudo-supervised adaptation, --adapt).

    .venv/Scripts/python.exe occ_lab/msw_t2.py --stage fit --tag m0
    .venv/Scripts/python.exe occ_lab/msw_t2.py --stage lab --tag m0
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

LAB = Path(__file__).resolve().parent
sys.path.insert(0, str(LAB))
import longctx as LC  # noqa: E402

import numpy as np  # noqa: E402
import torch  # noqa: E402
import torch.nn as nn  # noqa: E402
import torch.nn.functional as Fn  # noqa: E402

C, cnn = LC.C, LC.cnn
H, F, DEV = LC.H, LC.F, LC.DEV
CACHE, MODELS = LC.CACHE, LC.MODELS
CROP = 64


class MSW(nn.Module):
    def __init__(self, cin, c=64):
        super().__init__()
        self.tenc = nn.Sequential(nn.Conv1d(cin, c, 3, padding=1), nn.GELU(),
                                  nn.Conv1d(c, c, 3, padding=2, dilation=2), nn.GELU(),
                                  nn.Conv1d(c, c, 3, padding=4, dilation=4), nn.GELU())
        self.senc = nn.Sequential(nn.Conv1d(2 * c, c, 5, padding=2), nn.GELU(), nn.Conv1d(c, c, 5, padding=2), nn.GELU())
        self.init = nn.Conv1d(c + 2, 1, 1)
        self.haz = nn.Sequential(nn.Conv1d(c + 5 + 1, c, 1), nn.GELU(), nn.Conv1d(c, 2, 1))

    def forward(self, x):                                    # x (B, Cin, H, S) -> pi (B, F, S)
        B, Ci, Hh, S = x.shape
        seq = x.permute(0, 3, 1, 2).reshape(B * S, Ci, Hh).float()
        e = self.tenc(seq)                                   # (B S, c, H)
        e = torch.cat([e[:, :, -1], e.mean(2)], 1).view(B, S, -1).permute(0, 2, 1)
        h = self.senc(e)                                     # (B, c, S)
        last_q, last_o = x[:, 3, -1].float(), x[:, 2, -1].float()
        z0 = self.init(torch.cat([h, (last_q * 2 - 1)[:, None], last_o[:, None]], 1))[:, 0]
        pi = torch.sigmoid(z0)
        outs = []
        for k in range(1, F + 1):
            nb = torch.stack([torch.roll(pi, r, 1) for r in (-2, -1, 0, 1, 2)], 1)
            kk = torch.full((B, 1, S), k / F, device=x.device)
            on, off = torch.sigmoid(self.haz(torch.cat([h, nb, kk], 1))).unbind(1)
            pi = pi * (1 - off) + (1 - pi) * on
            outs.append(pi)
        return torch.stack(outs, 1).clamp(1e-5, 1 - 1e-5)


def loss_fn(pi, y, m):
    bce = (Fn.binary_cross_entropy(pi, y, reduction="none") * m).sum() / m.sum().clamp(min=1)
    lg = torch.log(pi) - torch.log1p(-pi)
    return bce + 0.5 * cnn.lovasz_hinge(lg, y, m)


def batch(parts, idx, bs, rng):
    xs, ys, ms = [], [], []
    for _ in range(bs):
        k = rng.integers(len(parts))
        p = parts[k]
        j = rng.choice(idx[k])
        d, t0 = p["d"][j:j + 1], p["t0"][j:j + 1]
        x = LC.short_x(p, d, t0)
        fi = t0[:, None] + np.arange(1, F + 1)
        y, m = p["q"][d[:, None], fi], p["el"][d[:, None], fi]
        S = x.shape[-1]
        a = rng.integers(0, max(1, S - CROP + 1))
        sl = slice(a, a + CROP)
        xs.append(LC.crop(x, sl, S)); ys.append(LC.crop(y, sl, S)); ms.append(LC.crop(m, sl, S))
    t = lambda a: torch.from_numpy(np.concatenate(a).astype(np.float32)).to(DEV)  # noqa: E731
    return t(xs), t(ys), t(ms)


def stage_fit(args):
    rng = np.random.default_rng(args.seed)
    torch.manual_seed(args.seed)
    parts = LC.train_panels()
    tr, es = [], []
    for p in parts:
        n_on = len(p["ctx"].eo[0])
        og = np.arange(len(p["d"])) >= n_on
        tr.append(np.flatnonzero(og & ~p["es"])); es.append(np.flatnonzero(og & p["es"]))
    x0, _, _ = batch(parts, tr, 2, rng)
    net = MSW(x0.shape[1]).to(DEV)
    opt = torch.optim.AdamW(net.parameters(), lr=args.lr, weight_decay=1e-4)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, args.lr, total_steps=args.steps)
    ev_rng = np.random.default_rng(99)
    ev = [batch(parts, es, 32, ev_rng) for _ in range(8)]
    best, t_start = 1e9, time.time()
    for step in range(1, args.steps + 1):
        net.train()
        xb, yb, mb = batch(parts, tr, 32, rng)
        loss = loss_fn(net(xb), yb, mb)
        opt.zero_grad(set_to_none=True); loss.backward()
        nn.utils.clip_grad_norm_(net.parameters(), 1.0)
        opt.step(); sched.step()
        if step % 500 == 0:
            net.eval()
            with torch.no_grad():
                eb = float(np.mean([(Fn.binary_cross_entropy(net(x), y, reduction="none") * m).sum().item() /
                                    max(m.sum().item(), 1) for x, y, m in ev]))
            if eb < best:
                best = eb
                torch.save({"state": net.state_dict(), "cin": x0.shape[1]}, MODELS / f"msw_{args.tag}.pt")
            print(f"  step {step}: loss {loss.item():.4f}  ES bce {eb:.4f} (best {best:.4f}) ({time.time() - t_start:.0f}s)",
                  flush=True)


@torch.no_grad()
def predict(net, x, bs=16):
    net.eval()
    return np.concatenate([net(C.to_dev(x[a:a + bs])).cpu().numpy() for a in range(0, len(x), bs)])


def stage_lab(args):
    d_ = torch.load(MODELS / f"msw_{args.tag}.pt", map_location=DEV)
    net = MSW(d_["cin"]).to(DEV)
    net.load_state_dict(d_["state"])
    res = {}
    for i, panel in enumerate(C.T2_PANELS):
        ctx, stat, W = C.windows(i, panel)
        for s in C.SPLITS:
            og, z = W[s]["og"], W[s]["z"]
            x = C.make_x(ctx, stat, og, np.arange(len(og["d"])), z)
            p = predict(net, x)
            np.savez(CACHE / f"fam_msw_{args.tag}_{s}_{panel}.npz", og=p.astype(np.float16))
            sc = C.ongoing_iou(p, og, 0.5)
            res.setdefault(s, {})[panel] = (sc.mean(), sc[og["d"] <= 4].mean())
        print(f"  {panel}: " + "  ".join(f"{s[:4]} {res[s][panel][0]:.4f}" for s in C.SPLITS), flush=True)
    for s in C.SPLITS:
        print(f"{s}: msw alone all {C.family_mean({k: v[0] for k, v in res[s].items()}):.4f}  days 1-5 "
              f"{C.family_mean({k: v[1] for k, v in res[s].items()}):.4f}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", choices=["fit", "lab"], required=True)
    ap.add_argument("--tag", default="m0")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--steps", type=int, default=12000)
    ap.add_argument("--lr", type=float, default=2e-3)
    args = ap.parse_args()
    (stage_fit if args.stage == "fit" else stage_lab)(args)


if __name__ == "__main__":
    main()
